// Builds desktop/plugin.js from desktop/src/plugin.js by inlining stage/guest.html as a data: URL.
// No bundler: the source is already plain ESM that only imports @hermes/plugin-sdk and react.
//   node scripts/build.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'desktop', 'src', 'plugin.js'), 'utf8')
const guest = readFileSync(join(root, 'stage', 'guest.html'), 'utf8')
// The card's frame gets a policy that blocks every network request: scripts, styles and data may
// only come from the page itself or from blob:/data: URLs the harness makes. The exported HTML
// file keeps the marker as a comment, because it loads three.js from a CDN.
const CSP = "default-src 'none'; script-src 'unsafe-inline' blob:; style-src 'unsafe-inline'; img-src blob: data:; media-src blob: data:; font-src blob: data:; connect-src blob: data:; worker-src blob:"
if (!guest.includes('<!--CSP-->')) throw new Error('marker <!--CSP--> missing from stage/guest.html')
const sealed = guest.replace('<!--CSP-->', `<meta http-equiv="Content-Security-Policy" content="${CSP}">`)
const url = 'data:text/html;base64,' + Buffer.from(sealed, 'utf8').toString('base64')
if (!src.includes("'__GUEST_URL__'")) throw new Error('marker __GUEST_URL__ missing from desktop/src/plugin.js')
const out = '// GENERATED by scripts/build.mjs from desktop/src/plugin.js and stage/guest.html. Do not edit.\n' +
  src.replace("'__GUEST_URL__'", JSON.stringify(url))

const target = join(root, 'desktop', 'plugin.js')
if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch {}
  if (current !== out) { console.error('desktop/plugin.js is stale: run node scripts/build.mjs'); process.exit(1) }
  console.log('desktop/plugin.js is up to date')
} else {
  writeFileSync(target, out)
  console.log(`wrote desktop/plugin.js (${(out.length / 1024).toFixed(1)} KiB)`)
}
